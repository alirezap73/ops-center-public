const BUMP = {
  large: [1, 0, 0],
  medium: [0, 1, 0],
  small: [0, 0, 1],
};

/** نسخه‌ی تجمعی بعد از هر ردیف — هم‌ترتیب با خودِ entries */
export function computeVersions(entries = CHANGELOG) {
  let major = 0, minor = 0, patch = 0;
  return entries.map((entry) => {
    const [dMajor, dMinor, dPatch] = BUMP[entry.size] || BUMP.small;
    if (dMajor) {
      major += dMajor; minor = 0; patch = 0;
    } else if (dMinor) {
      minor += dMinor; patch = 0;
    } else {
      patch += dPatch;
    }
    return `${major}.${minor}.${patch}`;
  });
}

export function computeVersion(entries = CHANGELOG) {
  const versions = computeVersions(entries);
  return versions[versions.length - 1] || "0.0.0";
}
